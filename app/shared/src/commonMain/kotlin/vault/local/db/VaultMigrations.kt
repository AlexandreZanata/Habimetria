package vault.local.db

import androidx.room.migration.Migration
import androidx.sqlite.SQLiteConnection
import androidx.sqlite.execSQL

// v1 → v2: shutter-time location details plus a separate EXIF claim.
// Pure ADD COLUMN migration: every existing row survives with nulls
// (isMocked defaults to false). Destructive migration stays forbidden.
val MIGRATION_1_2 = object : Migration(1, 2) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL("ALTER TABLE evidences ADD COLUMN fixAgeMs INTEGER")
        connection.execSQL("ALTER TABLE evidences ADD COLUMN provider TEXT")
        connection.execSQL("ALTER TABLE evidences ADD COLUMN accuracyLevel TEXT")
        connection.execSQL("ALTER TABLE evidences ADD COLUMN isMocked INTEGER NOT NULL DEFAULT 0")
        connection.execSQL("ALTER TABLE evidences ADD COLUMN exifLatitude REAL")
        connection.execSQL("ALTER TABLE evidences ADD COLUMN exifLongitude REAL")
    }
}

// v2 → v3: manifests table with a unique inspection binding. Existing
// inspections stay DRAFT; nothing is sealed by the migration itself.
val MIGRATION_2_3 = object : Migration(2, 3) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL(
            "CREATE TABLE IF NOT EXISTS `manifests` (`id` TEXT NOT NULL, `inspectionId` TEXT NOT NULL, " +
                "`formatVersion` INTEGER NOT NULL, `canonicalSha256` TEXT NOT NULL, " +
                "`canonicalJson` TEXT NOT NULL, `sealedAtDevice` TEXT NOT NULL, " +
                "`signerKeyId` TEXT NOT NULL, `algorithm` TEXT NOT NULL, " +
                "`hardwareBacked` INTEGER NOT NULL, `signature` TEXT NOT NULL, PRIMARY KEY(`id`), " +
                "FOREIGN KEY(`inspectionId`) REFERENCES `inspections`(`id`) " +
                "ON UPDATE NO ACTION ON DELETE NO ACTION )",
        )
        connection.execSQL(
            "CREATE UNIQUE INDEX IF NOT EXISTS `index_manifests_inspectionId` " +
                "ON `manifests` (`inspectionId`)",
        )
    }
}

// v3 → v4: reports table with a unique manifest binding plus the
// detached receipt columns. No report is generated by migration.
val MIGRATION_3_4 = object : Migration(3, 4) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL(
            "CREATE TABLE IF NOT EXISTS `reports` (`id` TEXT NOT NULL, `inspectionId` TEXT NOT NULL, " +
                "`manifestId` TEXT NOT NULL, `manifestSha256` TEXT NOT NULL, `status` TEXT NOT NULL, " +
                "`pdfSha256` TEXT, `pdfFileName` TEXT, `receiptSignature` TEXT, " +
                "`signerKeyId` TEXT NOT NULL, `algorithm` TEXT NOT NULL, " +
                "`hardwareBacked` INTEGER NOT NULL, `createdAtDevice` TEXT NOT NULL, " +
                "`completedAtDevice` TEXT, PRIMARY KEY(`id`), " +
                "FOREIGN KEY(`inspectionId`) REFERENCES `inspections`(`id`) " +
                "ON UPDATE NO ACTION ON DELETE NO ACTION , " +
                "FOREIGN KEY(`manifestId`) REFERENCES `manifests`(`id`) " +
                "ON UPDATE NO ACTION ON DELETE NO ACTION )",
        )
        connection.execSQL(
            "CREATE UNIQUE INDEX IF NOT EXISTS `index_reports_manifestId` " +
                "ON `reports` (`manifestId`)",
        )
    }
}

// v4 → v5: trusted issuers. Trust starts empty on every install;
// nothing is ever trusted by migration.
val MIGRATION_4_5 = object : Migration(4, 5) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL(
            "CREATE TABLE IF NOT EXISTS `trusted_issuers` (`keyId` TEXT NOT NULL, " +
                "`label` TEXT NOT NULL, `source` TEXT NOT NULL, " +
                "`addedAtDevice` TEXT NOT NULL, PRIMARY KEY(`keyId`))",
        )
    }
}

// v5 → v6: occurrences timeline per property. No backfill; new rows
// only. Sealed inspections are untouched by definition.
val MIGRATION_5_6 = object : Migration(5, 6) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL(
            "CREATE TABLE IF NOT EXISTS `occurrences` (`id` TEXT NOT NULL, " +
                "`propertyId` TEXT NOT NULL, `title` TEXT NOT NULL, `body` TEXT, " +
                "`createdAtDevice` TEXT NOT NULL, PRIMARY KEY(`id`), " +
                "FOREIGN KEY(`propertyId`) REFERENCES `properties`(`id`) " +
                "ON UPDATE NO ACTION ON DELETE NO ACTION )",
        )
        connection.execSQL(
            "CREATE INDEX IF NOT EXISTS `index_occurrences_propertyId` " +
                "ON `occurrences` (`propertyId`)",
        )
        connection.execSQL(
            "CREATE TABLE IF NOT EXISTS `occurrence_attachments` (`id` TEXT NOT NULL, " +
                "`occurrenceId` TEXT NOT NULL, `fileName` TEXT NOT NULL, " +
                "`mime` TEXT NOT NULL, `size` INTEGER NOT NULL, `sha256` TEXT NOT NULL, " +
                "`capturedAtDevice` TEXT NOT NULL, `note` TEXT, PRIMARY KEY(`id`), " +
                "FOREIGN KEY(`occurrenceId`) REFERENCES `occurrences`(`id`) " +
                "ON UPDATE NO ACTION ON DELETE NO ACTION )",
        )
        connection.execSQL(
            "CREATE INDEX IF NOT EXISTS `index_occurrence_attachments_occurrenceId` " +
                "ON `occurrence_attachments` (`occurrenceId`)",
        )
    }
}
